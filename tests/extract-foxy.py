"""Pack decoded game animation frames without resizing, retiming or changing pixels."""
import json
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
clips = {}
for key, filename in [("fnaf2", "fnaf2-foxy"), ("sister-location", "fnafsl-foxy"), ("fnaf6", "fnaf6-foxy")]:
    source = Image.open(root / "assets" / f"{filename}.webp")
    width, height = source.size
    columns = 4
    atlas = Image.new("RGBA", (width * columns, height * ((source.n_frames + columns - 1) // columns)))
    durations = []
    for index in range(source.n_frames):
        source.seek(index)
        frame = source.convert("RGBA")
        if frame.getchannel("A").getextrema()[0] != 0:
            raise ValueError(f"{filename} frame {index} is not transparent")
        durations.append(source.info["duration"])
        atlas.paste(frame, ((index % columns) * width, (index // columns) * height))
    atlas.save(root / "assets" / f"{filename}-atlas.webp", lossless=True, exact=True)
    clips[key] = {"atlas": f"modules/lumiel-jumpscare-tools/assets/{filename}-atlas.webp", "width": width,
                  "height": height, "columns": columns, "durations": durations}
    print(f"{key}: {source.n_frames} frames, {sum(durations)} ms, {width}x{height}, original RGBA")
for key in ["fnaf1", "fnaf4"]:
    files = sorted((root / "assets/sources" / key).glob("*.png"), key=lambda p: int(p.stem))
    frames = [Image.open(file).convert("RGBA") for file in files]
    if key == "fnaf1":
        frames = [frame.crop((94, 0, 650, 720)) for frame in frames]
    width, height = frames[0].size
    durations = [20] * (len(frames) - 1) + [340] if key == "fnaf1" else [40] * len(frames)
    atlas = Image.new("RGBA", (width * 4, height * ((len(frames) + 3) // 4)))
    for index, frame in enumerate(frames):
        atlas.paste(frame, ((index % 4) * width, (index // 4) * height))
    atlas.save(root / "assets" / f"{key}-foxy-atlas.webp", lossless=True, exact=True)
    clips[key] = {"atlas": f"modules/lumiel-jumpscare-tools/assets/{key}-foxy-atlas.webp",
                  "masks": f"modules/lumiel-jumpscare-tools/assets/{key}-foxy-masks.json",
                  "width": width, "height": height, "columns": 4, "durations": durations}
    if key == "fnaf1":
        clips[key]["align"] = "left center"
        # Replace the office cobweb over the ear using its adjacent-frame texture.
        clips[key]["repairs"] = [{"frame": 3, "sourceFrame": 4,
            "sourcePath": "M40,63L60,67L84,79L110,97L128,118L136,139L132,149L109,157L84,152L65,143L50,126L43,107Z",
            "targetPath": "M0,78L25,86L47,101L61,123L69,140L59,148L42,151L16,144L0,134Z",
            "transform": [.95, 0, 0, .82, -62, 23]}]
    print(f"{key}: {len(frames)} source frames, {sum(durations)} ms")
(root / "scripts/foxy-data.js").write_text("// Generated by tests/extract-foxy.py.\nexport const FOXY_CLIPS = " + json.dumps(clips, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
